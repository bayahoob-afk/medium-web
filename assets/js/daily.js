    const yStr = y.getFullYear() + "-" + (y.getMonth() + 1) + "-" + y.getDate();
    const streak = c.lastDate === yStr ? c.streak + 1 : 1;
    lsSet(LS_CHECKIN, { lastDate: t, streak });
